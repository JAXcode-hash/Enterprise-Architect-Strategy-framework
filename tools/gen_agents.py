def render_master(h: dict, smes: dict[str, list[dict]]) -> str:
    m = h["master"]
    proto = h["protocols"]
    art = proto["artefact"]["master"]
    doms = sorted(h["domains"], key=lambda d: d["order"])

    rows = [f"| `architect-{d['id']}` | **{d['code']}** {d['name']} | {len(smes[d['id']])} | "
            f"{', '.join(d['eas_domains']) or '_not covered by the engine_'} |" for d in doms]

    L = [
        "---",
        "name: master-architect",
        "description: >-",
        "  Master Security Architect. Use to oversee and evaluate the output of the twelve Domain",
        "  Architects, reconcile cross-domain dependencies, adjudicate contradictions between",
        "  domains, and grade a whole-estate security position. Engage for anything spanning more",
        "  than one security domain, or to assess a complete architecture direction. Does not do",
        "  domain work - routes it to the owning Domain Architect.",
        f"tools: {MASTER_TOOLS}",
        "---",
        "",
        MARK,
        "",
        "# Master Security Architect",
        "",
        "**Tier 0** &nbsp;|&nbsp; **Oversees** 12 Domain Architects, "
        f"{sum(len(v) for v in smes.values())} SMEs",
        "",
        m["role"],
        "",
        "## The team",
        "",
        "| Architect | Domain | SMEs | Engine domains |",
        "|---|---|---|---|",
        *rows,
        "",
        "Four domains have no counterpart in the Enterprise Architect Strategy engine — "
        "offensive security, human and organisational, physical and environmental, and emerging "
        "and specialised. A base plate run does not assess them at all, so their Architects' "
        "output is the only coverage the estate has there. Treat a whole-estate position that "
        "never engaged them as incomplete rather than clean.",
        "",
        "## When you are engaged",
        "",
        *bullets(m["engages_when"]),
        "",
        "You are not the first port of call. A question that lives inside one domain goes to "
        "that Domain Architect, who resolves it with their SMEs. You see what they could not "
        "resolve without another domain.",
        "",
        "## How you work",
        "",
        "### 1. Evaluate, do not redo",
        "",
        "Read each Domain Architect's output and assess its quality, not just its content:",
        "",
        "- Did they engage the SMEs the request actually touched?",
        "- Did they reconcile disagreement, or average it?",
        "- Did they carry questions forward with owners, or quietly close them?",
        "- Is anything asserted about another domain rather than stated as a dependency?",
        "",
        "A domain output with no questions against a thin brief has assumed something. Send it "
        "back and ask what.",
        "",
        "### 2. Reconcile across domains",
        "",
        "Build the dependency picture between domains and classify each:",
        "",
        "| State | Meaning |",
        "|---|---|",
        "| **Satisfied** | One domain needs something, another domain's position supplies it, and both describe the same thing. |",
        "| **Contradiction** | Two domains have taken positions that cannot both hold. Blocking. |",
        "| **Gap** | A domain needs something no domain supplies. Becomes a question with an owner. |",
        "| **Assumed** | Two domains have each assumed the other handles it. The most dangerous state, because both outputs look complete. |",
        "",
        "The **Assumed** state is the one only you can find. Neither Domain Architect can see it, "
        "because from inside each domain the assumption looks like a reasonable reading of the "
        "other's scope.",
        "",
        "### 3. Route questions, never answer them",
        "",
        *bullets(m["never"]),
        "",
        "### 4. Grade",
        "",
        "| Verdict | Meaning |",
        "|---|---|",
        "| **Coherent** | No contradictions, no assumed dependencies, every gap has a named owner and a date. |",
        "| **Conditional** | Coherent but with named open questions gating specific decisions. |",
        "| **Not yet** | Contradictions or assumed dependencies remain between domains. |",
        "",
        "## What you return",
        "",
        *[f"{i}. **{part}**" for i, part in enumerate(art, start=1)],
        "",
        "## Working with the engine",
        "",
        "The Enterprise Architect Strategy engine covers nine of the twelve domains with a "
        "catalogued option set, cross-domain compatibility rules and volumetric anchors. It is "
        "deterministic and does the mechanical reconciliation in under a second:",
        "",
        "```bash",
        "python3 -m eas new --brief <path>     # intake, fan-out, fan-in, render",
        "python3 -m eas run <project-id>       # re-reconcile after a change",
        "python3 -m eas lint                   # the catalogue must be coherent first",
        "```",
        "",
        "Use it for the domains it covers, then engage the Domain Architects to check its "
        "reasoning and to cover the four domains it does not reach. Never edit generated output "
        "under `projects/<id>/outputs/` by hand — change `brief.md` or `inputs/` and re-run, so "
        "the change flows through the reconciliation and lands in the ledgers.",
        "",
        "## Framework anchors",
        "",
        f"- **CISSP** — {h['framework_anchors']['cissp']}",
        f"- **NIST CSF 2.0** — {h['framework_anchors']['nist_csf_2']}",
        "",
        "---",
        "",
        "*An unresolved dependency is a finding with an owner. It is never a gap for you to fill "
        "with a reasonable assumption — that is precisely the failure this tier exists to "
        "prevent.*",
        "",
    ]
    return "\n".join(L)


# --------------------------------------------------------------------------

def lint(h: dict, smes: dict[str, list[dict]]) -> list[str]:
    problems: list[str] = []
    domain_ids = {d["id"] for d in h["domains"]}
    all_sme_ids: dict[str, str] = {}

    for dom in h["domains"]:
        for other in dom.get("interfaces_with", []):
            if other not in domain_ids:
                problems.append(f"{dom['id']}: interfaces_with unknown domain {other!r}")
            if other == dom["id"]:
                problems.append(f"{dom['id']}: interfaces_with itself")

    for dom_id, items in smes.items():
        for s in items:
            if s["id"] in all_sme_ids:
                problems.append(f"duplicate SME id {s['id']!r} in {dom_id} and "
                                f"{all_sme_ids[s['id']]}")
            all_sme_ids[s["id"]] = dom_id
            for field in ("owns", "authoritative_on", "never_assume", "must_ask",
                          "escalate_when", "produces"):
                if not s.get(field):
                    problems.append(f"{s['id']}: empty {field}")
            for q in s.get("must_ask", []):
                if not q.get("of"):
                    problems.append(f"{s['id']}: a must_ask question has no owner")

    for dom_id, items in smes.items():
        local = {s["id"] for s in items}
        for s in items:
            for p in s.get("peers", []):
                if p not in local:
                    problems.append(
                        f"{s['id']}: peer {p!r} is not in the same domain - a peer must be a "
                        f"same-domain SME, cross-domain goes through escalation")
            if s["id"] in s.get("peers", []):
                problems.append(f"{s['id']}: lists itself as a peer")
    return problems


def main() -> int:
    h, smes = load()
    problems = lint(h, smes)
    if problems:
        print("refusing to generate from an incoherent org catalogue:", file=sys.stderr)
        for p in problems:
            print(f"  - {p}", file=sys.stderr)
        return 1

    AGENTS.mkdir(parents=True, exist_ok=True)
    # Clear previously generated agents so a removed SME does not linger.
    for old in AGENTS.glob("*.md"):
        if MARK in old.read_text(encoding="utf-8"):
            old.unlink()

    all_domains = {d["id"]: d for d in h["domains"]}
    written = 0

    (AGENTS / "master-architect.md").write_text(render_master(h, smes), encoding="utf-8")
    written += 1

    for dom in sorted(h["domains"], key=lambda d: d["order"]):
        (AGENTS / f"architect-{dom['id']}.md").write_text(
            render_architect(h, dom, smes[dom["id"]], all_domains), encoding="utf-8")
        written += 1
        peers = {s["id"]: s["name"] for s in smes[dom["id"]]}
        for sme in smes[dom["id"]]:
            (AGENTS / f"sme-{sme['id']}.md").write_text(
                render_sme(h, dom, sme, peers), encoding="utf-8")
            written += 1

    print(f"wrote {written} agents to {AGENTS}")
    print(f"  1 master, {len(h['domains'])} domain architects, "
          f"{sum(len(v) for v in smes.values())} SMEs")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
