#!/usr/bin/env python3
"""Generate the security architecture team from the org catalogue.

Three tiers, eighty agents:

    1  master-architect      evaluates and reconciles across domains
   12  architect-<domain>    orchestrates, compiles, validates, sense-checks
   67  sme-<capability>      capability depth, working in isolation

The routing and escalation protocol is stamped verbatim into every agent from
`catalogue/org/hierarchy.json`, so an SME's understanding of when to escalate
cannot drift from its Architect's understanding of when to accept.

    python3 tools/gen_agents.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
AGENTS = ROOT / ".claude" / "agents"
ORG = ROOT / "catalogue" / "org"
MARK = "<!-- generated by tools/gen_agents.py - edit catalogue/org/, not this file -->"

SME_TOOLS = "Read, Grep, Glob, WebSearch, WebFetch"
ARCHITECT_TOOLS = "Read, Grep, Glob, Bash, WebSearch, WebFetch"
MASTER_TOOLS = "Read, Write, Edit, Bash, Grep, Glob, WebSearch, WebFetch"


def load() -> tuple[dict, dict[str, list[dict]]]:
    hierarchy = json.loads((ORG / "hierarchy.json").read_text(encoding="utf-8"))
    smes: dict[str, list[dict]] = {}
    for dom in hierarchy["domains"]:
        path = ORG / "smes" / f"{dom['id']}.json"
        if not path.is_file():
            raise SystemExit(f"missing SME file for domain {dom['id']}: {path}")
        raw = json.loads(path.read_text(encoding="utf-8"))
        if raw["domain"] != dom["id"]:
            raise SystemExit(f"{path} declares domain {raw['domain']!r}, expected {dom['id']!r}")
        smes[dom["id"]] = raw["smes"]
    return hierarchy, smes


def bullets(items: list[str], prefix: str = "- ") -> list[str]:
    return [f"{prefix}{i}" for i in items]


# --------------------------------------------------------------------------
# SME agents
# --------------------------------------------------------------------------

def render_sme(h: dict, dom: dict, sme: dict, peers: dict[str, str]) -> str:
    proto = h["protocols"]
    art = proto["artefact"]["sme"]
    peer_lines = [f"- `sme-{p}` — {peers[p]}" for p in sme.get("peers", []) if p in peers]

    L = [
        "---",
        f"name: sme-{sme['id']}",
        "description: >-",
        f"  {sme['name']} SME within the {dom['name']} domain. Use when a question needs",
        f"  capability depth on {sme['name'].lower()} specifically. Works in isolation and returns",
        "  a position, the assumptions it refused to make, and the questions that must be answered",
        "  before its position is safe to rely on. Routing requests go back to",
        f"  `architect-{dom['id']}`, never directly to another SME.",
        f"tools: {SME_TOOLS}",
        "---",
        "",
        MARK,
        "",
        f"# {sme['name']}",
        "",
        f"**Tier 2 — SME** &nbsp;|&nbsp; **Domain** {dom['name']} (`{dom['code']}`) "
        f"&nbsp;|&nbsp; **Reports to** `architect-{dom['id']}`",
        "",
        f"{sme['owns']}",
        "",
        "## You are authoritative on",
        "",
        *bullets(sme["authoritative_on"]),
        "",
        "## How you work",
        "",
        *[f"{i}. {rule}" for i, rule in enumerate(proto["sme"], start=1)],
        "",
        "## What you must never assume",
        "",
        "These are the specific things that look settled and are not. Where one applies and you "
        "have not been told the answer, it becomes a question in your output — never a "
        "placeholder value and never a reasonable-sounding guess.",
        "",
        *bullets(sme["never_assume"]),
        "",
        "## Questions you always put",
        "",
        "| Question | Owner |",
        "|---|---|",
        *[f"| {q['q']} | {q['of']} |" for q in sme["must_ask"]],
        "",
        "## Routing",
        "",
        "### Same domain — request via your Architect",
        "",
    ]
    L += peer_lines or ["- _No same-domain peers registered for this capability._"]
    L += [
        "",
        "You do not contact a peer yourself. Return a routing request naming the SME and the "
        "specific question, and let `architect-" + dom["id"] + "` decide whether to make it.",
        "",
        "### Cross domain — escalate, do not resolve",
        "",
        "Return these to your Architect as dependencies. They go to the Master Architect, not to "
        "you, and you must not assume an answer in the meantime:",
        "",
        *bullets(sme["escalate_when"]),
        "",
        "## What you return",
        "",
        *[f"{i}. **{part}**" for i, part in enumerate(art, start=1)],
        "",
        "Concretely, this capability produces:",
        "",
        *bullets(sme["produces"]),
        "",
        "---",
        "",
        f"*Domain scope: {dom['scope']}*",
        "",
        "*Isolation is deliberate. You have been engaged for depth in one capability; a position "
        "you offer outside it carries none of that depth and displaces the SME who would have "
        "given a better one.*",
        "",
    ]
    return "\n".join(L)


